#!/usr/bin/env bash
# usage: tests/gen-script-reference.sh [ROOT]      writes docs/reference/scripts.md to stdout
# The reference is the header comment of every script under skills/*/scripts/, quoted verbatim.
# Nothing is parsed or paraphrased, so the page cannot disagree with the script, and
# tests/reference.test.sh fails when the committed page is not what this prints.
# Regenerate:  tests/gen-script-reference.sh > docs/reference/scripts.md
export LC_ALL=C
root=${1:-$(cd "$(dirname "$0")/.." && pwd)}
cat <<'H'
<!-- SPDX-FileCopyrightText: 2026 Georges Martin <jrjsmrtn@gmail.com> -->
<!-- SPDX-License-Identifier: MIT -->
<!-- Generated by tests/gen-script-reference.sh from the scripts' header comments. Do not edit by hand. -->

# Script reference

Each skill that ships a check keeps it in its own `scripts/` directory. This page quotes the header comment of
every one of them, unchanged: usage, exit codes, what it checks and what it leaves to you. The scripts are the
authority; this page is generated from them.

Copy a script into your project and run it from the repository root, as its skill's Validation section says.

H
for f in "$root"/skills/*/scripts/*.sh; do
  [ -f "$f" ] || continue
  skill=$(basename "$(dirname "$(dirname "$f")")")
  name=$(basename "$f")
  hdr=$(awk 'NR == 1 && /^#!/ { next } /^#/ { sub(/^# ?/, ""); print; next } { exit }' "$f")
  case $hdr in
    *'```'*)
      echo "gen-script-reference: $name header contains a code fence" >&2
      exit 1
      ;;
  esac
  [ -n "$hdr" ] || {
    echo "gen-script-reference: $name has no header comment" >&2
    exit 1
  }
  printf '## `%s`\n\nFrom [`%s`](../../skills/%s/SKILL.md). [Source](../../skills/%s/scripts/%s).\n\n```text\n%s\n```\n\n' \
    "$name" "$skill" "$skill" "$skill" "$name" "$hdr"
done
echo "## Related"
echo
echo "- [Why the skills ship checks, not just instructions](../explanation/why-checks-fail-instead-of-instruct.md)"
echo "  explains why these scripts exist."
echo "- [How a check is built and proved](../explanation/how-a-check-is-built-and-proved.md) explains how each is tested."
